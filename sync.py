#!/usr/bin/env python3
"""Install the editor settings and profiles tracked in this repository."""

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent
PROFILES = {
    "web": ("Web", "code"),
    "ruby": ("Ruby", "ruby"),
    "python": ("Python", "snake"),
    "java": ("Java", "coffee"),
    "go": ("Go", "go"),
    "elixir": ("Elixir", "beaker"),
    "ruby-focus": ("Ruby Focus", "eye-closed"),
    "rust-focus": ("Rust Focus", "flame"),
}
BASES = {"ruby-focus": "ruby"}
SHARED = dict.fromkeys(
    ("keybindings", "snippets", "tasks", "mcp", "prompts", "languageModels"), True
)


def load_jsonc(path):
    # Source files use whole-line comments; JSON strings remain untouched.
    source = re.sub(r"^[ \t]*//.*$", "", path.read_text(), flags=re.MULTILINE)
    return json.loads(source)


def settings_body(settings, sources):
    header = "// GENERATED by vscode-setup/sync.py\n"
    header += "// Edit " + " and ".join(sources) + " in the repo, then rerun sync.py\n"
    return header + json.dumps(settings, indent=2) + "\n"


def write_file(path, body, dry_run):
    if path.exists() and path.read_text() == body:
        print(f"unchanged {path}")
        return
    print(f"{'would write' if dry_run else 'writing'} {path}")
    if dry_run:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    backup = path.with_name(path.name + ".vscode-setup.bak")
    if path.exists() and not backup.exists():
        shutil.copy2(path, backup)
    temporary = path.with_name(path.name + ".vscode-setup.tmp")
    temporary.write_text(body)
    temporary.replace(path)


def extension_ids(key):
    return [line.strip() for line in (ROOT / "extensions" / f"{key}.txt").read_text().splitlines()
            if line.strip() and not line.startswith("#")]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="show changes without writing files or installing extensions")
    parser.add_argument("--skip-extensions", action="store_true", help="only sync settings and profiles")
    parser.add_argument("--user-dir", type=Path, default=Path.home() / "Library/Application Support/Code/User",
                        help="VS Code User directory (also useful for testing)")
    args = parser.parse_args()
    user = args.user_dir.expanduser()
    storage_path = user / "globalStorage" / "storage.json"
    if not storage_path.is_file():
        parser.error(f"{storage_path} does not exist; install and launch VS Code once, then quit it")

    core = load_jsonc(ROOT / "core.jsonc")
    profile_settings = {key: load_jsonc(ROOT / f"{key}.jsonc") for key in PROFILES}
    manifests = {key: extension_ids(key) for key in ("default", *PROFILES)}
    storage = json.loads(storage_path.read_text())
    entries = storage.setdefault("userDataProfiles", [])

    # Register profiles before asking the CLI to install extensions into them.
    for key, (name, icon) in PROFILES.items():
        location = f"{key}-prof"
        entry = next((item for item in entries if item.get("name") == name), None)
        if entry is None:
            entry = {"location": location, "name": name, "icon": icon}
            entries.append(entry)
        elif entry.get("location") != location:
            parser.error(f"profile {name!r} already uses {entry.get('location')!r}; resolve this before syncing")
        entry["useDefaultFlags"] = SHARED.copy()

    write_file(storage_path, json.dumps(storage, indent=2) + "\n", args.dry_run)
    write_file(user / "settings.json", settings_body(core, ["core.jsonc"]), args.dry_run)
    for filename in ("keybindings.json", "mcp.json"):
        write_file(user / filename, (ROOT / filename).read_text(), args.dry_run)

    for key in PROFILES:
        base = profile_settings[BASES[key]] if key in BASES else {}
        merged = {**core, **base, **profile_settings[key]}
        sources = ["core.jsonc"]
        if key in BASES:
            sources.append(f"{BASES[key]}.jsonc")
        sources.append(f"{key}.jsonc")
        directory = user / "profiles" / f"{key}-prof"
        write_file(directory / "settings.json", settings_body(merged, sources), args.dry_run)
        if not args.dry_run:
            (directory / "globalStorage").mkdir(parents=True, exist_ok=True)

    if args.dry_run or args.skip_extensions:
        for key, ids in manifests.items():
            print(f"{key}: {len(ids)} extensions in manifest")
        return

    code = shutil.which("code")
    if not code:
        parser.error("VS Code's 'code' command is not on PATH; install it from the Command Palette")
    failures = []
    for key, ids in manifests.items():
        profile = [] if key == "default" else ["--profile", PROFILES[key][0]]
        result = subprocess.run([code, *profile, "--list-extensions"], capture_output=True, text=True)
        if result.returncode:
            failures.append(f"{key}: could not list extensions: {result.stderr.strip()}")
            continue
        installed = {line.strip().lower() for line in result.stdout.splitlines()}
        for extension in ids:
            if extension.lower() in installed:
                continue
            print(f"installing {extension} in {key}", flush=True)
            result = subprocess.run([code, *profile, "--install-extension", extension], capture_output=True, text=True)
            if result.returncode:
                failures.append(f"{key}: {extension}: {result.stderr.strip()}")
    if failures:
        print("\n".join(failures), file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
